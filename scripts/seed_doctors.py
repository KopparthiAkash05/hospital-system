"""Seed the MediCare Hospital doctor directory.

The script is idempotent: it can be run as often as needed without creating
duplicates.

    python scripts/seed_doctors.py --dry-run          # show the plan only
    python scripts/seed_doctors.py                    # write to the database
    python scripts/seed_doctors.py --emit-sql         # write database/seed_doctors.sql
    python scripts/seed_doctors.py --emit-docs        # write database/SEED_CREDENTIALS.md
    python scripts/seed_doctors.py --update-existing  # also refresh seeded doctors

The credentials come from ``scripts/doctor_seed_data.py``; the same data
produces the generated SQL file, so both stay in sync.
"""

import argparse
import os
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from dotenv import load_dotenv  # noqa: E402
from werkzeug.security import generate_password_hash  # noqa: E402

import doctor_seed_data as seed_data  # noqa: E402

DATABASE_DIR = ROOT / 'database'


def load_db_config():
    """Database credentials from the environment or the local details.env."""
    load_dotenv(ROOT / 'details.env')
    load_dotenv()

    config = {
        'host': os.environ.get('MYSQL_HOST'),
        'user': os.environ.get('MYSQL_USER'),
        'password': os.environ.get('MYSQL_PASSWORD'),
        'database': os.environ.get('MYSQL_DB'),
    }
    missing = [key for key, value in config.items() if not value]
    if missing:
        raise SystemExit(
            'Missing database settings: ' + ', '.join(missing) +
            '. Set them in details.env or the environment.'
        )
    return config


def connect(config):
    import pymysql
    return pymysql.connect(
        host=config['host'],
        user=config['user'],
        password=config['password'],
        database=config['database'],
        charset='utf8mb4',
        autocommit=False,
    )


def sql_string(value):
    """Escapes a value for a single quoted SQL string."""
    if value is None:
        return 'NULL'
    return "'" + str(value).replace("\\", "\\\\").replace("'", "''") + "'"


# --------------------------------------------------------------------- SQL file

def build_sql(records):
    """The idempotent SQL script that seeds the same data."""
    lines = []
    lines.append('-- MediCare Hospital - doctor directory seed')
    lines.append('-- Generated by scripts/seed_doctors.py --emit-sql')
    lines.append(f'-- Generated on: {datetime.now().strftime("%Y-%m-%d %H:%M")}')
    lines.append('--')
    lines.append('-- Every statement is safe to run repeatedly:')
    lines.append('--   * departments use INSERT IGNORE (name is unique)')
    lines.append('--   * doctors are inserted only when the email is new')
    lines.append('--   * schedules use INSERT IGNORE (doctor + day + start is unique)')
    lines.append('--')
    lines.append('-- Passwords are scrypt hashes of the demo passwords listed in')
    lines.append('-- database/SEED_CREDENTIALS.md. The phone numbers are demo placeholders')
    lines.append('-- from the 89 / 63 / 78 mobile blocks.')
    lines.append('')
    lines.append('SET NAMES utf8mb4;')
    lines.append('')
    lines.append('START TRANSACTION;')
    lines.append('')

    lines.append('-- 1. Departments -----------------------------------------------------------')
    lines.append('INSERT IGNORE INTO Department (name, description, is_active) VALUES')
    department_values = [
        f"  ({sql_string(name)}, {sql_string(description)}, 1)"
        for name, description in seed_data.DEPARTMENT_DESCRIPTIONS.items()
    ]
    lines.append(',\n'.join(department_values) + ';')
    lines.append('')

    lines.append('-- 2. Doctors ---------------------------------------------------------------')
    lines.append('INSERT INTO Doctor (')
    lines.append('    name, specialization, experience, email, password, phone, city,')
    lines.append('    available_slots, latitude, longitude, address, department_id,')
    lines.append('    qualification, license_number, consultation_fee, profile_description,')
    lines.append('    availability_status, is_active')
    lines.append(')')
    lines.append('SELECT')
    lines.append('    s.name, s.specialization, s.experience, s.email, s.password, s.phone,')
    lines.append('    s.city, s.available_slots, s.latitude, s.longitude, s.address,')
    lines.append('    dp.department_id, s.qualification, s.license_number,')
    lines.append('    s.consultation_fee, s.profile_description,')
    lines.append("    'Available', 1")
    lines.append('FROM (')
    rows = []
    for record in records:
        rows.append(
            "    SELECT {name} AS name, {specialization} AS specialization, "
            "{experience} AS experience, {email} AS email, {password} AS password, "
            "{phone} AS phone, {city} AS city, {available_slots} AS available_slots, "
            "{latitude} AS latitude, {longitude} AS longitude, {address} AS address, "
            "{qualification} AS qualification, {license_number} AS license_number, "
            "{consultation_fee} AS consultation_fee, {profile_description} AS profile_description"
            .format(
                name=sql_string(record['name']),
                specialization=sql_string(record['specialization']),
                experience=record['experience'],
                email=sql_string(record['email']),
                password=f"CAST({sql_string(record['password_hash'])} AS CHAR(255))",
                phone=sql_string(record['phone']),
                city=sql_string(record['city']),
                available_slots=f"CAST({sql_string(record['available_slots'])} AS CHAR(255))",
                latitude=record['latitude'],
                longitude=record['longitude'],
                address=f"CAST({sql_string(record['address'])} AS CHAR(255))",
                qualification=f"CAST({sql_string(record['qualification'])} AS CHAR(255))",
                license_number=sql_string(record['license_number']),
                consultation_fee=sql_string(record['consultation_fee']),
                profile_description=(
                    f"CAST({sql_string(record['profile_description'])} AS CHAR(1000))"
                ),
            )
        )
    lines.append('\n    UNION ALL\n'.join(rows))
    lines.append(') AS s')
    lines.append('LEFT JOIN Department dp ON dp.name = s.specialization')
    lines.append('WHERE NOT EXISTS (SELECT 1 FROM Doctor d WHERE d.email = s.email);')
    lines.append('')

    lines.append('-- 3. Weekly working schedules ----------------------------------------------')
    lines.append('-- The two doctors that existed before this seed keep their free text')
    lines.append('-- availability; these rows simply mirror it so the automatic')
    lines.append('-- availability engine works for them as well.')
    lines.append('INSERT IGNORE INTO DoctorSchedule')
    lines.append('    (doctor_id, day_of_week, start_time, end_time, slot_duration, is_active)')
    lines.append('SELECT d.doctor_id, s.day_of_week, s.start_time, s.end_time,')
    lines.append('       s.slot_duration, 1')
    lines.append('FROM (')
    schedule_rows = []
    for record in records:
        for day_of_week, start, end in record['schedule']:
            schedule_rows.append(
                "    SELECT {email} AS email, {day} AS day_of_week, "
                "CAST({start} AS CHAR(8)) AS start_time, CAST({end} AS CHAR(8)) AS end_time, "
                "{duration} AS slot_duration"
                .format(
                    email=sql_string(record['email']),
                    day=day_of_week,
                    start=sql_string(f'{start}:00'),
                    end=sql_string(f'{end}:00'),
                    duration=seed_data.SLOT_DURATION,
                )
            )
    for email, windows in seed_data.EXISTING_DOCTOR_SCHEDULES.items():
        for day_of_week, start, end in windows:
            schedule_rows.append(
                "    SELECT {email} AS email, {day} AS day_of_week, "
                "CAST({start} AS CHAR(8)) AS start_time, CAST({end} AS CHAR(8)) AS end_time, "
                "{duration} AS slot_duration"
                .format(
                    email=sql_string(email),
                    day=day_of_week,
                    start=sql_string(f'{start}:00'),
                    end=sql_string(f'{end}:00'),
                    duration=seed_data.SLOT_DURATION,
                )
            )
    lines.append('\n    UNION ALL\n'.join(schedule_rows))
    lines.append(') AS s')
    lines.append('JOIN Doctor d ON d.email = s.email;')
    lines.append('')
    lines.append('COMMIT;')
    lines.append('')
    return '\n'.join(lines)


def build_credentials_doc(records):
    """The developer facing list of demo logins."""
    lines = []
    lines.append('# Seeded doctor credentials')
    lines.append('')
    lines.append('Demo logins for the doctors added by `scripts/seed_doctors.py`.')
    lines.append('Generated by `python scripts/seed_doctors.py --emit-docs`.')
    lines.append('')
    lines.append('## Pattern')
    lines.append('')
    lines.append('| Field | Value |')
    lines.append('| --- | --- |')
    lines.append('| Email | `<name>@gmail.com` (lower case, no spaces) |')
    lines.append('| Password | `doctor123<name>` (lower case, no spaces) |')
    lines.append('| Phone | demo placeholders from the 89 / 63 / 78 mobile blocks |')
    lines.append('')
    lines.append('Example: Dr. Ananya Sharma -> `ananyasharma@gmail.com` / '
                 '`doctor123ananyasharma`.')
    lines.append('')
    lines.append('> The phone numbers are demo placeholders. They use the 89 / 63 / 78')
    lines.append('> mobile blocks with a zero padded tail so they read as test data;')
    lines.append('> they are not meant for real calls or SMS.')
    lines.append('')
    lines.append('> These are demo accounts for a development database. Change the')
    lines.append('> passwords before using any of this data in a real deployment.')
    lines.append('')
    lines.append('## Doctors')
    lines.append('')
    lines.append('| # | Name | Department | Email | Password | Phone | Working hours |')
    lines.append('| --- | --- | --- | --- | --- | --- | --- |')
    for index, record in enumerate(records, start=1):
        lines.append(
            f"| {index} | Dr. {record['name']} | {record['department']} | "
            f"`{record['email']}` | `{record['password']}` | `{record['phone']}` | "
            f"{record['available_slots']} |"
        )
    lines.append('')
    lines.append('## Existing doctors')
    lines.append('')
    lines.append('| Name | Email | Working hours |')
    lines.append('| --- | --- | --- |')
    lines.append('| Dr. Smith | `smith@gmail.com` | Mon-Fri: 9AM-5PM, Sat: 10AM-4PM |')
    lines.append('| Dr. David | `david@gmail.com` | Mon-Fri: 10AM-5PM |')
    lines.append('')
    return '\n'.join(lines)


# ------------------------------------------------------------------ database run

def seed_database(config, records, update_existing=False, dry_run=False):
    """Insert the doctors and their schedules. Returns a summary dict."""
    connection = connect(config)
    summary = {
        'departments_created': 0,
        'doctors_created': 0,
        'doctors_updated': 0,
        'doctors_skipped': 0,
        'schedules_created': 0,
    }

    try:
        with connection.cursor() as cursor:
            # Departments -------------------------------------------------
            cursor.execute('SELECT name FROM Department')
            existing_departments = {row[0] for row in cursor.fetchall()}

            for name, description in seed_data.DEPARTMENT_DESCRIPTIONS.items():
                if name in existing_departments:
                    continue
                if not dry_run:
                    cursor.execute(
                        'INSERT IGNORE INTO Department (name, description, is_active) '
                        'VALUES (%s, %s, 1)', (name, description)
                    )
                summary['departments_created'] += 1

            # Doctors -----------------------------------------------------
            cursor.execute('SELECT email, doctor_id FROM Doctor')
            existing_doctors = {row[0]: row[1] for row in cursor.fetchall()}

            for record in records:
                if record['email'] in existing_doctors:
                    if update_existing and not dry_run:
                        cursor.execute(
                            '''UPDATE Doctor
                               SET name = %s, specialization = %s, experience = %s,
                                   phone = %s, city = %s, available_slots = %s,
                                   latitude = %s, longitude = %s, address = %s,
                                   department_id = (
                                       SELECT department_id FROM Department
                                       WHERE name = %s
                                   ),
                                   qualification = %s, license_number = %s,
                                   consultation_fee = %s, profile_description = %s,
                                   availability_status = %s, is_active = %s
                               WHERE doctor_id = %s''',
                            (
                                record['name'], record['specialization'], record['experience'],
                                record['phone'], record['city'], record['available_slots'],
                                record['latitude'], record['longitude'], record['address'],
                                record['department'],
                                record['qualification'], record['license_number'],
                                record['consultation_fee'], record['profile_description'],
                                record['availability_status'], record['is_active'],
                                existing_doctors[record['email']],
                            )
                        )
                        summary['doctors_updated'] += 1
                    else:
                        summary['doctors_skipped'] += 1
                    continue

                if dry_run:
                    summary['doctors_created'] += 1
                    continue

                cursor.execute(
                    '''INSERT INTO Doctor
                       (name, specialization, experience, email, password, phone, city,
                        available_slots, latitude, longitude, address, department_id,
                        qualification, license_number, consultation_fee,
                        profile_description, availability_status, is_active)
                       VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s,
                               (SELECT department_id FROM Department WHERE name = %s),
                               %s, %s, %s, %s, %s, %s)''',
                    (
                        record['name'], record['specialization'], record['experience'],
                        record['email'], record['password_hash'], record['phone'],
                        record['city'], record['available_slots'], record['latitude'],
                        record['longitude'], record['address'], record['department'],
                        record['qualification'], record['license_number'],
                        record['consultation_fee'], record['profile_description'],
                        record['availability_status'], record['is_active'],
                    )
                )
                summary['doctors_created'] += 1

            # Schedules ---------------------------------------------------
            schedule_rows = []
            for record in records:
                for day_of_week, start, end in record['schedule']:
                    schedule_rows.append((record['email'], day_of_week, start, end))
            for email, windows in seed_data.EXISTING_DOCTOR_SCHEDULES.items():
                for day_of_week, start, end in windows:
                    schedule_rows.append((email, day_of_week, start, end))

            emails = sorted({row[0] for row in schedule_rows})
            placeholders = ', '.join(['%s'] * len(emails))
            cursor.execute(
                f'''SELECT d.email, ds.day_of_week, TIME_FORMAT(ds.start_time, '%%H:%%i:%%s')
                    FROM DoctorSchedule ds
                    JOIN Doctor d ON d.doctor_id = ds.doctor_id
                    WHERE d.email IN ({placeholders})''',
                tuple(emails)
            )
            existing_schedules = {
                (row[0], row[1], row[2]) for row in cursor.fetchall()
            }

            missing = [
                (email, day_of_week, f'{start}:00', f'{end}:00')
                for email, day_of_week, start, end in schedule_rows
                if (email, day_of_week, f'{start}:00') not in existing_schedules
            ]

            if missing and not dry_run:
                cursor.execute(
                    f'SELECT doctor_id, email FROM Doctor WHERE email IN ({placeholders})',
                    tuple(emails)
                )
                doctor_ids = {row[1]: row[0] for row in cursor.fetchall()}

                values = ', '.join(['(%s, %s, %s, %s, %s, 1)'] * len(missing))
                params = []
                for email, day_of_week, start, end in missing:
                    doctor_id = doctor_ids.get(email)
                    if doctor_id is None:
                        continue
                    params.extend(
                        [doctor_id, day_of_week, start, end, seed_data.SLOT_DURATION]
                    )
                if params:
                    cursor.execute(
                        f'''INSERT IGNORE INTO DoctorSchedule
                            (doctor_id, day_of_week, start_time, end_time,
                             slot_duration, is_active)
                            VALUES {values}''',
                        tuple(params)
                    )
                    summary['schedules_created'] = cursor.rowcount or 0
            else:
                summary['schedules_created'] = len(missing)

        if not dry_run:
            connection.commit()
        else:
            connection.rollback()
    finally:
        connection.close()

    return summary


def main():
    parser = argparse.ArgumentParser(description='Seed the doctor directory.')
    parser.add_argument('--dry-run', action='store_true',
                        help='report what would happen without writing anything')
    parser.add_argument('--emit-sql', action='store_true',
                        help='write database/seed_doctors.sql')
    parser.add_argument('--emit-docs', action='store_true',
                        help='write database/SEED_CREDENTIALS.md')
    parser.add_argument('--update-existing', action='store_true',
                        help='refresh the profile of doctors that are already seeded')
    args = parser.parse_args()

    records = seed_data.doctor_records()
    for record in records:
        record['password_hash'] = generate_password_hash(record['password'])

    if args.emit_sql or args.emit_docs:
        DATABASE_DIR.mkdir(exist_ok=True)
        if args.emit_sql:
            path = DATABASE_DIR / 'seed_doctors.sql'
            path.write_text(build_sql(records), encoding='utf-8')
            print(f'Wrote {path.relative_to(ROOT)}')
        if args.emit_docs:
            path = DATABASE_DIR / 'SEED_CREDENTIALS.md'
            path.write_text(build_credentials_doc(records), encoding='utf-8')
            print(f'Wrote {path.relative_to(ROOT)}')

    if args.emit_sql and args.emit_docs:
        return

    summary = seed_database(load_db_config(), records,
                            update_existing=args.update_existing,
                            dry_run=args.dry_run)
    prefix = 'Would create' if args.dry_run else 'Created'
    print(
        f"{prefix}: {summary['doctors_created']} doctors, "
        f"{summary['departments_created']} departments, "
        f"{summary['schedules_created']} schedule rows"
    )
    if summary['doctors_updated']:
        print(f"Updated: {summary['doctors_updated']} doctors")
    if summary['doctors_skipped']:
        print(f"Skipped (already present): {summary['doctors_skipped']} doctors")


if __name__ == '__main__':
    main()
